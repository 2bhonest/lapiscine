#include <unistd.h>

int	main(int count, char **v)
{
	int	i;
	int	j;

	i = 1;
	while (count - i > 0)
	{
		j = 0;
		while (v[count - i][j])
		{
			write(1, &v[count - i][j], 1);
			j++;
		}
		i++;
		write(1, "\n", 1);
	}
	return (0);
}
