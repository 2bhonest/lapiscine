#include <unistd.h>
#include <stdio.h>

int	ft_sqrt(int nb)
{
	int	n;

	n = 0;
	while (n * n < nb)
	{
		if (2147483647 / (n + 1) < n + 1)
			break ;
		n++;
	}
	if (nb == n * n)
		return (n);
	return (0);
}
