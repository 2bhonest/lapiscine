#include <unistd.h>

void	ft_write(char n1, char n2, int a[])
{
	if (a[2] != 0)
	{
		write(1, " ", 1);
	}
	write(1, &n1, 1);
	write(1, &n2, 1);
	if (a[3] % 2 != 0)
	{
		if (a[1] != 98)
		{
			write(1, ",", 1);
		}
	}
}

void	ft_print_comb2(void)
{
	char	n[4];
	int		a[4];

	a[0] = 0;
	a[1] = 0;
	a[2] = 0;
	while (a[1] <= 98)
	{
		a[0] = a[1] + 1;
		n[1] = a[1] % 10 + '0';
		n[0] = a[1] / 10 + '0';
		while (a[0] <= 99)
		{
			a[3] = 0;
			n[3] = a[0] % 10 + '0';
			n[2] = a[0] / 10 + '0';
			ft_write(n[0], n[1], a);
			a[2]++;
			a[3]++;
			ft_write(n[2], n[3], a);
			a[0]++;
		}
		a[1]++;
	}
}
